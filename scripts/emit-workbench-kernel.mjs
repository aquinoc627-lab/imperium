#!/usr/bin/env node
/**
 * Bundle web/v0/src/browser-api.ts → web/workbench/kernel.js
 * so the static workbench can call the reference kernel without a runtime bundler.
 *
 * Requires esbuild on PATH or in node_modules. Not a runtime dependency.
 */
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const entry = path.join(root, "web/v0/src/browser-api.ts");
const outfile = path.join(root, "web/workbench/kernel.js");

function resolveEsbuild() {
  const candidates = [
    path.join(root, "node_modules/.bin/esbuild"),
    path.join(root, "web/v0/node_modules/.bin/esbuild"),
    "esbuild",
  ];
  for (const bin of candidates) {
    const probe = spawnSync(bin, ["--version"], { encoding: "utf8" });
    if (probe.status === 0) return bin;
  }
  return null;
}

const bin = resolveEsbuild();
if (!bin) {
  console.error(
    "emit-workbench-kernel: esbuild not found. Install it to regenerate web/workbench/kernel.js",
  );
  process.exit(1);
}

const result = spawnSync(
  bin,
  [
    entry,
    "--bundle",
    "--format=esm",
    "--platform=browser",
    "--target=es2022",
    "--minify",
    `--outfile=${outfile}`,
    "--legal-comments=none",
    "--banner:js=/* generated by scripts/emit-workbench-kernel.mjs from web/v0 — do not edit */",
  ],
  { stdio: "inherit" },
);

if (result.status !== 0) process.exit(result.status ?? 1);
console.log(`wrote ${path.relative(root, outfile)}`);
